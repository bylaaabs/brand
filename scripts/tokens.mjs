// generates generated/tokens/ from tokens/tokens.json, the one source of the design tokens.
//
//   npm run tokens   only the tokens (plain node, no inkscape, no dependencies)
//   npm run brand    everything, the tokens included
//
// one file per kit, each in the names that kit already uses:
//   tokens.css               ui-web (and every web through it): a tailwind @theme, --color-<name>, --font-<name>
//   swift/BrandTokens.swift  ui-swift: the hex values BrandColors is built from, the font families
//   android/BrandTokens.kt   ui-android: argb longs and the font families (a stub until the kit reads it)
//   winui/BrandTokens.xaml   ui-winui: a resource dictionary of colours, brushes and fonts (a stub too)
import { mkdir, readFile, writeFile, rm } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const out = join(root, 'generated', 'tokens')
const source = JSON.parse(await readFile(join(root, 'tokens', 'tokens.json'), 'utf8'))
const kits = ['web', 'swift', 'android', 'winui']

/** every token of a group as { key, value, description, names, platforms } */
const group = (name) =>
  Object.entries(source[name]).map(([key, t]) => {
    const ext = t.$extensions?.['com.laaabs'] ?? {}
    return { key, value: t.$value, description: t.$description, swift: ext.swift, platforms: ext.platforms ?? kits }
  })
const colors = group('color')
const fonts = group('font')

for (const c of colors) {
  if (!/^#[0-9a-f]{6}$/.test(c.value)) throw new Error(`color.${c.key}: ${c.value} is not a lowercase #rrggbb`)
  for (const p of c.platforms) if (!kits.includes(p)) throw new Error(`color.${c.key}: unknown platform ${p}`)
}

const camel = (k) => k.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase())
const pascal = (k) => camel(k).replace(/^./, (ch) => ch.toUpperCase())
const on = (kit) => (t) => t.platforms.includes(kit)
const head = (comment) => `${comment} generated by brand/scripts/tokens.mjs from brand/tokens/tokens.json. do not edit by hand.`
const hex = (v) => v.slice(1).toUpperCase()

await rm(out, { recursive: true, force: true })
for (const dir of ['swift', 'android', 'winui']) await mkdir(join(out, dir), { recursive: true })

// web: the names ui-web has always had, so the tailwind classes (bg-bg, text-cyan, bg-success/12) do not change
// the brand family and any name with a space quoted, the generic fallbacks bare: as ui-web wrote them
const cssFont = (v) => v.map((f, i) => (i === 0 || /\s/.test(f) ? `'${f}'` : f)).join(', ')
await writeFile(
  join(out, 'tokens.css'),
  `${head('/*')} */
@theme {
${colors
  .filter(on('web'))
  .map((c) => `  --color-${c.key}: ${c.value};`)
  .join('\n')}

${fonts.map((f) => `  --font-${f.key}: ${cssFont(f.value)};`).join('\n')}
}
`,
)

// swift: hex literals only, no SwiftUI, so BrandColors keeps its own Color / NSColor and colour spaces
await writeFile(
  join(out, 'swift', 'BrandTokens.swift'),
  `${head('//')}
// the solid values ui-swift's BrandColors is built from, in its names; tints stay derived there.

public enum BrandTokens {
    public enum Colors {
${colors
  .filter(on('swift'))
  .map((c) => `${c.description ? `        /// ${c.description}\n` : ''}        public static let ${c.swift ?? camel(c.key)}: UInt32 = 0x${hex(c.value)}`)
  .join('\n')}
    }

    public enum Fonts {
${fonts.map((f) => `        /// ${f.description}\n        public static let ${camel(f.key)} = "${f.value[0]}"`).join('\n')}
    }
}
`,
)

// android: argb longs, no compose dependency (Color(BrandTokens.Colors.success) in the kit)
await writeFile(
  join(out, 'android', 'BrandTokens.kt'),
  `${head('//')}
package com.laaabs.ui.tokens

object BrandTokens {
    object Colors {
${colors
  .filter(on('android'))
  .map((c) => `        const val ${camel(c.key)}: Long = 0xFF${hex(c.value)}`)
  .join('\n')}
    }

    object Fonts {
${fonts.map((f) => `        const val ${camel(f.key)} = "${f.value[0]}"`).join('\n')}
    }
}
`,
)

// winui: a colour and a brush per token, Laaabs<Name>Color / Laaabs<Name>Brush, and the font families
await writeFile(
  join(out, 'winui', 'BrandTokens.xaml'),
  `<!-- ${head('').trim()} -->
<ResourceDictionary
    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
${colors
  .filter(on('winui'))
  .map((c) => `    <Color x:Key="Laaabs${pascal(c.key)}Color">#FF${hex(c.value)}</Color>\n    <SolidColorBrush x:Key="Laaabs${pascal(c.key)}Brush" Color="#FF${hex(c.value)}" />`)
  .join('\n')}
${fonts.map((f) => `    <FontFamily x:Key="Laaabs${pascal(f.key)}Font">${f.value[0]}</FontFamily>`).join('\n')}
</ResourceDictionary>
`,
)

console.log('generated tokens')
